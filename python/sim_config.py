#   ≈½·0.77·0.25²≈2.4%（相对 tanh 列本身），折算到 fsc 约 1–2%，可接受。
#   真机 σ_v≈0.026 rad/s ⇒ 每趟窗内样本 n≳120（≈1.2 s 匀速段）就能满足；
#   SS_CV_TIME=3 s 给的就是这个量级。
# 相关性波动（漂移/极限环）不随 n 下降，由"前半 vs 后半"判据和力矩 SEM 一起卡。
SS_DTHETA_S_SEM_FRAC = 0.02      # θ̇_s 均值标准误 / |ω| 上限
SS_DTHETA_S_SEM_ABS = 0.0025     # θ̇_s 均值标准误绝对下限 [rad/s]（λ·该值 = 0.25）
SS_TS_SEM_FRAC = 0.05            # Ts 均值标准误 / |⟨Ts⟩| 上限
SS_TS_SEM_ABS = 1.0e-3           # Ts 均值标准误绝对下限 [N·m]
SS_VEL_TOL_ABS = 0.005           # 逐趟稳态判据绝对容差 [rad/s]
SS_DTHETA_B_RMS_MAX = 0.1        # 窗口内 θ̇_b RMS 上限 [rad/s]（大 yaw 晃太狠就丢）
SS_DDTHETA_B_RATE_MAX = 3.0      # 窗口内**平均**θ̈_b 上限 [rad/s²]（M12·⟨θ̈_b⟩ 会直接进 Ts）
#   注意：不能拿逐样本 θ̈_b RMS 当判据——它是带噪速度的差分，RMS ≈ √2·σ_v/dt
