# ---- 小 yaw 匀速往返摩擦实验（gen_friction_sweep_s.py）----
# 原理（与库内模型严格对应，见 dynamics.cpp 的关节 s 方程）
#     θ_b 被固定（θ̇_b≈θ̈_b≈0）、θ_s 在行程内以恒定 ω 往返、基座恒为 0 时：
#         Ts = G2(ψ_s) + fsv·ω + fsc·tanh(λ·ω)
#     对**同一段以 0 为中心对称的位置窗口**取正、反两趟：
#         ΔTs = Ts(+ω) − Ts(−ω) = fsv·Δω + fsc·Δtanh(λω)
#     G2 是位置的函数，两趟扫过同一对称区间，其一阶项精确抵消——因此不需要任何
#     已辨识的动力学/重力参数，也不怕 θ_b 有小漂移（漂移只影响高阶残差）。
#     关节 s 没有整圈行程（±35° 硬限位），所以拿"正反行程镜像"换大 yaw 的"整圈平均"。
#
# 行程与反向（绝不依赖电控在 ±35° 处的保护：那里力矩会被削弱，发出的力矩≠实际力矩）
#     * 往返幅值上限 = THETA_S_TARGET_DEG（±30°，主动控制范围，不再额外缩）；
#     * 反向用刹车距离判据 |θ_s| + v²/(2·SS_A_BRAKE) ≥ A，SS_A_BRAKE 远小于实机
#       可用角加速度，实际制动峰值只会到 ~25–28°；|θ_s| > THETA_S_TARGET_DEG 的样本
#       标记无效；|θ_s| > THETA_S_LIMIT_DEG **只作废那一趟**，速度继续跑
#       （超限是一次性事件，丢那一条数据即可）。
# 幅值按速度缩放（这是"带限位也能建立匀速"的关键）：
#     A(ω) = clip(ω·SS_CV_TIME/2 + ω²/(2·SS_A_BRAKE), SS_AMP_MIN_DEG, 幅值上限)
#   即每个速度的**匀速段只占 SS_CV_TIME 秒**；高速时幅值被上限截断、匀速段变短，
#   就用更多往返趟数补样本——每趟仍覆盖同一段位置，差分依然成立。
SS_OMEGA_LIST = list(OMEGA_LIST)   # 速度表：按 |ω| 去重，每个速度正反各扫
# ---- 最大可用角加速度标定（开始记录前做一次）----
