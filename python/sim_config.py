#   力矩刹停，对**加速段**（始终在 ±THETA_S_TARGET_DEG 内）拟合 θ(t)=θ0+v0t+½at²，
#   正反各一次算一组，来回 SS_AMAX_CYCLES 次取平均。正反平均后重力矩 G2 抵消。
#   标定结果有两个用途：
