SS_REPOS_TOL_RAD = 0.01          # 归位角度容差 [rad]（再小就被位置噪声卡住）
SS_REPOS_TOL_VEL = 0.05          # 归位速度容差 [rad/s]（必须**停稳**才算到位）
SS_REPOS_MAX_STEPS = 2000
SS_VEL_TOL_FRAC = 0.05           # 逐趟稳态判据相对容差（前半均值 vs 后半均值）
# ---- 窗口内的波动上限（"平均值"只有在波动小的时候才代表这一段）----
# 卡的是**窗口均值的标准误** σ/√n，不是逐样本 std。原因（实测）：真机上报角速度的
#   高频噪声底 ~0.026 rad/s，比 tanh 的转折尺度 1/λ=0.01 rad/s 还大；而辨识用的是
#   ⟨ω⟩（列里是 tanh(λ⟨ω⟩)），白噪声按 σ/√n 平均掉，卡逐样本 std 会把所有点都毙掉。
# 但噪声必须真能平均掉：tanh 是凸的，E[tanh(λ(ω̄+ε))] ≠ tanh(λω̄)，这个 Jensen 偏差
